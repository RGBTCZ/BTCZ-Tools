class I18N:
    def __init__(self):
        self.lang = self._load_lang()
        self._listeners = []

    def _load_lang(self):
        if SETTINGS_FILE.exists():
            try:
                data = json.loads(SETTINGS_FILE.read_text(encoding="utf-8"))
                lang = data.get("language", DEFAULT_LANG)
                if lang in LANGUAGES:
                    return lang
            except Exception:
                pass
        return DEFAULT_LANG

    def _save_lang(self):
        try:
            SETTINGS_FILE.write_text(
                json.dumps({"language": self.lang}, indent=2), encoding="utf-8"
            )
        except Exception:
            pass

    def set_language(self, lang):
        if lang not in LANGUAGES or lang == self.lang:
            return
        self.lang = lang
        self._save_lang()
        for listener in self._listeners:
            try:
                listener()
            except Exception:
                pass

    def add_listener(self, callback):
        self._listeners.append(callback)

    def t(self, key, **kwargs):
        table = TRANSLATIONS.get(self.lang, TRANSLATIONS[DEFAULT_LANG])
        template = table.get(key) or TRANSLATIONS[DEFAULT_LANG].get(key) or key
        if kwargs:
            try:
                return template.format(**kwargs)
            except Exception:
                return template
        return template


i18n = I18N()


def t(key, **kwargs):
    return i18n.t(key, **kwargs)
